-- 设置行号
vim.opt.number = true          -- 显示行号
vim.opt.relativenumber = false -- 相对行号（可选）

-- 缩进与制表符
vim.opt.tabstop = 4      -- Tab 显示为 4 空格
vim.opt.shiftwidth = 4   -- 自动缩进宽度
vim.opt.expandtab = true -- 将 Tab 转为空格
vim.opt.autoindent = true
vim.opt.smartindent = true

vim.opt.mouse = ""

vim.g.mapleader = " "
